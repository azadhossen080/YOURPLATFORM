object AppStringsRegistry {
    fun forCode(code: String): AppStrings {
        val base = code.substringBefore('_').lowercase()
        return when (base) {
            "bn" -> BengaliStrings
            "en" -> EnglishStrings
            "hi" -> HindiStrings
            "ur" -> UrduStrings
            "ar" -> ArabicStrings
            "es" -> SpanishStrings
            "fr" -> FrenchStrings
            "de" -> GermanStrings
            "ja" -> JapaneseStrings
            "ko" -> KoreanStrings
            else -> EnglishStrings
        }
    }

    fun isRtl(code: String): Boolean {
        val base = code.substringBefore('_').lowercase()
        return base == "ar" || base == "ur"
    }

    fun aiLanguageName(code: String): String {
        val base = code.substringBefore('_').lowercase()
        return when (base) {
            "bn" -> "Bengali"
            "en" -> "English"
            "hi" -> "Hindi"
            "ur" -> "Urdu"
            "ar" -> "Arabic"
            "es" -> "Spanish"
            "fr" -> "French"
            "de" -> "German"
            "ja" -> "Japanese"
            "ko" -> "Korean"
            else -> "English"
        }
    }
}
